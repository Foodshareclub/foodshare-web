import { assertEquals, assertRejects } from "@std/assert";
import { generateListingCover } from "../api-v1-products/lib/listing-cover-generation.ts";
import {
  type CoverDependencies,
  ensureListingCover,
} from "../api-v1-products/lib/listing-cover.ts";
import { RateLimitError, ServiceUnavailableError } from "../_shared/errors.ts";

const input = {
  title: "Camping stove",
  description: "Portable stove a@example.com",
  postType: "things",
  images: [],
};
const png = new Uint8Array([137, 80, 78, 71, 13, 10, 26, 10, 0, 0, 0, 0]);

Deno.test("Z.ai request uses supported image model and redacted title/description context", async () => {
  const result = await generateListingCover(input, {
    apiKey: "test-key",
    fetch: ((url, init) => {
      assertEquals(url, "https://api.z.ai/api/paas/v4/images/generations");
      assertEquals(init?.redirect, "error");
      const body = JSON.parse(String(init?.body));
      assertEquals(body.model, "glm-image");
      assertEquals(body.size, "1280x1280");
      assertEquals(body.prompt.includes("Camping stove"), true);
      assertEquals(body.prompt.includes("Portable stove"), true);
      assertEquals(body.prompt.includes("a@example.com"), false);
      return Promise.resolve(
        Response.json({
          data: [{ url: "https://images.example.org/temporary.png?token=private" }],
        }),
      );
    }) as typeof fetch,
  });
  assertEquals(result.model, "glm-image");
});

Deno.test("provider failures and invalid image URLs fail without reflecting provider secrets", async () => {
  for (
    const response of [
      new Response("secret provider details", { status: 429 }),
      Response.json({ data: [] }),
      Response.json({ data: [{ url: "http://images.example.org/a.png" }] }),
      Response.json({ data: [{ url: "https://user:secret@example.org/a.png" }] }),
    ]
  ) {
    const error = await assertRejects(() =>
      generateListingCover(input, {
        apiKey: "test-key",
        fetch: (() => Promise.resolve(response)) as typeof fetch,
      }), ServiceUnavailableError);
    assertEquals(error.message, "Cover generation failed");
  }
});

function dependencies(): CoverDependencies {
  return {
    quota: () => Promise.resolve(true),
    search: () => Promise.reject(new Error("No suitable licensed photo")),
    generate: () =>
      Promise.resolve({
        imageUrl: "https://example.org/temporary?secret=private",
        model: "glm-image",
      }),
    download: () => Promise.resolve(png),
    store: (path) =>
      Promise.resolve(`https://api.foodshare.club/storage/v1/object/public/food-images/${path}`),
    verify: () => Promise.resolve(png),
  };
}

Deno.test("generated fallback is persisted and verified with truthful provenance and no temporary URL", async () => {
  const result = await ensureListingCover(input, "owner", dependencies());
  assertEquals(result.images[0].includes("owner/generated-covers/"), true);
  assertEquals(result.cover?.kind, "generated");
  assertEquals(result.cover?.provider, "zai");
  assertEquals(result.cover?.license, undefined);
  assertEquals(result.cover?.confidence, undefined);
  assertEquals(JSON.stringify(result).includes("secret=private"), false);
  assertEquals(
    result.cover?.disclosure,
    "AI-generated illustration; not a photograph of the listed item",
  );
});

Deno.test("exhausted quota calls neither provider", async () => {
  const deps = dependencies();
  deps.quota = () => Promise.resolve(false);
  deps.generate = () => {
    throw new Error("Paid provider must not be called");
  };
  await assertRejects(() => ensureListingCover(input, "owner", deps), RateLimitError);
});

Deno.test("generated bytes must pass the same raster and public readback checks as references", async () => {
  const invalid = dependencies();
  invalid.download = () => Promise.resolve(new TextEncoder().encode("not an image"));
  invalid.store = () => {
    throw Error("Invalid generated bytes must not be stored");
  };
  await assertRejects(() => ensureListingCover(input, "owner", invalid), Error, "raster");
  const mismatched = dependencies();
  mismatched.verify = () => Promise.resolve(new Uint8Array([1]));
  await assertRejects(() => ensureListingCover(input, "owner", mismatched), Error, "readback");
});
