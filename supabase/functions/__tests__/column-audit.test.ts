/**
 * Column audit: every column the code names, against the real schema.
 *
 * PostgREST rejects an entire statement when one column does not exist. A
 * single wrong name therefore does not degrade a field — it fails the whole
 * query, and what happens next depends on the caller:
 *
 *   * if the caller checks `error`, the feature is down, loudly. The profile
 *     handler turned its error into a 404, so it answered "not found" for
 *     every profile including the caller's own.
 *   * if the caller ignores `error`, the query returns nothing and the code
 *     carries on as though the answer were "none". `reviews.rating` made every
 *     user look unreviewed; `forum_reactions.reaction_type` made the toggle
 *     always take the "insert" branch, which then failed too.
 *
 * Both failure modes were found by hand. This test is what stops the next one
 * from being found by a user.
 *
 * ## What this reads
 *
 * `catalog.json`, generated by applying the migration corpus to a real
 * PostgreSQL 17 (`docs/oracle.md`). Not the migration text. The previous
 * version of this audit parsed the text with regular expressions and
 * reconstructed the schema itself, which is a second implementation of
 * PostgreSQL's DDL in a language nobody type-checks — and the record of how
 * that goes is in `docs/rls-audit.md`.
 *
 * ## The blind spot this closes
 *
 * The parser answered with `Map.get()`, and `undefined` meant two different
 * things: "no such relation" and "a relation whose columns are not readable".
 * The caller could not tell them apart, so it treated them the same way:
 *
 * ```ts
 * const known = columns.get(table);
 * if (!known || opaque.has(table)) continue;    // ← 28 relations, never checked
 * ```
 *
 * Twenty-eight relations across eighteen files went entirely unchecked,
 * including every table the engagement API reads, and the audit was silent
 * rather than green-and-wrong only because it printed nothing. `read.ts` makes
 * absence a value with a `reason`, so this audit now has to say which of the
 * three situations it is in, and only one of them lets it move on.
 *
 * ## Coverage is reported, not assumed
 *
 * `Coverage` counts what was read and what could not be, and a floor is pinned
 * on the first. An audit that examines nothing and an audit that finds nothing
 * must not look alike.
 */

import { assert, assertEquals } from "https://deno.land/std@0.208.0/assert/mod.ts";

import { assertCatalogIsCurrent, Coverage, schema } from "../../oracle/read.ts";
import {
  bucketTargets,
  literalKeys,
  scanCallSites,
  selectedColumns,
  selectedEmbeds,
  tableTargets,
} from "./lib/client-calls.ts";

const s = schema();
const sites = scanCallSites();
const coverage = new Coverage();

