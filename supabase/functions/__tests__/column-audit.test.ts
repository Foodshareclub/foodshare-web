Deno.test("column audit: the select parser tells embeds from columns", () => {
  // The first version of this audit read `author:profiles(id)` as three column
  // names, and the resulting list was mostly embedded relations.
  assertEquals(
    selectedColumns(
      "id, author:profiles!inner(id, nickname), posts:post_id (id, title)",
    ),
    ["id"],
    "aliases, !fk hints and embed bodies are not columns",
  );
  assertEquals(
    selectedColumns("id, post_name, images, is_active, created_at"),
    ["id", "post_name", "images", "is_active", "created_at"],
  );
  assertEquals(
    selectedColumns("*, count"),
    [],
    "`count` is a PostgREST keyword, not a column on anything",
  );
  // Per PostgREST's grammar `alias:relation(...)`, so `posts:post_id` embeds a
  // relation literally named `post_id`. That shape came from the previous
  // audit's own test case and is not a valid embed — the alias is `posts` and
  // the relation is `post_id`, and there is no such relation. The shape the
  // corpus actually uses is `author:profiles!inner(...)`.
  assertEquals(
    selectedEmbeds(
      "id, author:profiles!inner(id, nickname), comments:comments!post_id(id)",
    ).map((e) => e.relation),
    ["profiles", "comments"],
  );
});

Deno.test("column audit: the object-literal reader takes top-level keys only", () => {
  assertEquals(
    literalKeys("{ id, created_at, post_name }"),
    ["id", "created_at", "post_name"],
  );
  assertEquals(
    literalKeys("{ profile: { id, email }, role: 'admin' }"),
    ["profile", "role"],
    "a nested key is a value of `profile`, not a column named `id`",
  );
  assertEquals(
    literalKeys("{ ...base, updated_at: now }"),
    ["updated_at"],
    "a spread contributes no known key",
  );
  assertEquals(
    literalKeys("{ a: [1, 2], b: { c: 1 }, d: 4 }"),
    ["a", "b", "d"],
    "a comma inside a nested value does not end the key",
  );
  assertEquals(
    literalKeys(`{
      // the column is description, not details
      reason: input.reason,
      description: input.details || null,
    }`),
    ["reason", "description"],
    "prose in a comment is not a column. It was, once: the reader walked " +
      "through the comment explaining this very rename and reported the word " +
      "'and' as a missing column.",
  );
  assertEquals(
    literalKeys("someVariable"),
    null,
    "a payload that is not a literal must be reported as unreadable, not as empty",
  );
});
