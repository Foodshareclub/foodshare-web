/**
 * Selects and filters naming a column the schema does not define.
 *
 * Reported rather than failed on, for the same reason as the relations above:
 * production may have columns no migration creates, and this test can only see
 * the repository. What it must not do is let the list grow — each new entry is
 * a query that fails at runtime.
 *
 * Remove an entry when the code is corrected or the column is added.
 */
const KNOWN_MISSING_COLUMNS: Record<string, string[]> = {
  // `profiles.feature_flags` and `profiles.is_premium` have no source column;
  // the translation context handler reads them.
  "api-v1-localization/handlers/translations.ts": [
    "feature_flags",
    "is_premium",
  ],
  // `display_name` is derived from first/second name, not stored.
  "_shared/display-name/display-name-service.ts": ["display_name"],
  // No equivalent column; device_tokens has no enabled/disabled flag.
  "api-v1-notifications/lib/channels/push.ts": ["is_active"],
  // Neither column is on categories; both look like they belong to a joined
  // relation. Needs a decision about which table is meant.
  "api-v1-search/lib/text-search.ts": ["category_id", "profile_id"],
};

interface Finding {
  file: string;
  line: number;
  relation: string;
  columns: string[];
  kind: "select" | "filter" | "order" | "write" | "embed";
}

function missingColumns(): Finding[] {
  const out: Finding[] = [];
  const seen = new Set<string>();

  const push = (f: Finding) => {
    const key = `${f.file}|${f.relation}|${f.kind}|${f.columns.join(",")}`;
    if (seen.has(key)) return;
    seen.add(key);
    out.push(f);
  };

  for (const [key, group] of tableTargets(sites)) {
    const bare = key.split(".").pop()!;
    if (key.includes(".") && key.split(".")[0] !== "public") continue;

    // Resolved as `public.<name>`, for the same reason as above: PostgREST is
    // pinned to the `public` schema, so a bare name has exactly one meaning to
    // the client and the catalog has one relation with that name in *any*
    // schema. Resolving across all of them matched `api_requests` to
    // `metrics.api_requests` — a two-column stand-in — and reported a missing
    // `created_at` on a table the statement never touches.
    const rel = s.relation(`public.${bare}`);
    if (!rel.ok) {
      // Absent or opaque: nothing to check, and the relation audit is what
      // reports it. Counted as unchecked rather than quietly dropped.
      coverage.skipped(`${rel.reason}: ${bare}`);
      for (let i = 0; i < group.length; i++) coverage.readOne();
      continue;
    }

    const known = new Set(rel.value.columns.map((c) => c.name));
    for (const site of group) {
      coverage.readOne();
      const missing: string[] = [];

      if (site.select) {
        for (const c of selectedColumns(site.select)) {
          if (!known.has(c)) missing.push(c);
        }
      }
      for (const c of site.filters) {
        if (!known.has(c)) missing.push(c);
      }
      for (const c of site.orders) {
        if (!known.has(c)) missing.push(c);
      }
      for (const c of site.writes) {
        if (!known.has(c)) missing.push(c);
      }
      if (site.writesOpaque) {
        // A payload built at runtime cannot be read. Counted, not skipped
        // silently — this is the case an audit most easily pretends it checked.
        coverage.skipped(`opaque write payload: ${bare}`);
      }

      if (missing.length) {
        push({
          file: site.file,
          line: site.line,
          relation: bare,
          columns: [...new Set(missing)].sort(),
          kind: site.select
            ? "select"
            : site.writes.length
            ? "write"
            : site.orders.length
            ? "order"
            : "filter",
        });
      }
    }
  }
  return out;
}

Deno.test("column audit: no select, filter, order or write names a column the schema does not define", () => {
  assertCatalogIsCurrent(s);
  const findings = missingColumns();

  const unexpected: string[] = [];
  for (const f of findings) {
    const listed = KNOWN_MISSING_COLUMNS[f.file];
    if (!listed) {
      unexpected.push(
        `${f.file}:${f.line}  ${f.relation} (${f.kind}) uses ${
          f.columns.join(", ")
        } — no such column`,
      );
      continue;
    }
    const extra = f.columns.filter((c) => !listed.includes(c));
    if (extra.length) {
      unexpected.push(
        `${f.file}:${f.line}  ${f.relation} uses ${extra.join(", ")}, ` +
          "which is not in KNOWN_MISSING_COLUMNS for that file",
      );
    }
  }

  assertEquals(
    unexpected,
    [],
    "These name columns the schema does not define. PostgREST rejects the whole " +
      "statement, so the query returns nothing — loudly if the caller checks " +
      "`error`, silently (as zero) if it does not.\n" +
      unexpected.map((u) => `  - ${u}`).join("\n"),
  );
});

Deno.test("column audit: the catalog is checked against a corpus, not a sample", () => {
  // The floor is what distinguishes "checked everything and found nothing" from
  // "checked nothing". It is a tenth of the measured value so ordinary growth
  // passes and a structural break does not: a parser that stopped matching, a
  // scan that stopped walking, a catalog that lost its columns.
  assert(
    coverage.read > 200,
    `only ${coverage.read} call sites could be checked; something stopped ` +
      "matching. The previous version of this audit reported success while " +
      "checking none of 28 relations.\n" + coverage.summary(),
  );
  assert(
    sites.length > 300,
    `only ${sites.length} call sites found in the functions directory. ` +
      "A scan that silently stopped walking looks identical to a clean run.",
  );
});

Deno.test("column audit: what it could not check is reported, not hidden", () => {
  // Not a failure — a disclosure. The numbers are asserted so they cannot
  // quietly change, which is the only way a reader can tell that "0 findings"
  // means what it says.
  const reasons = coverage.reasons();
  const opaque = reasons.filter(([r]) => r.startsWith("opaque write"));
  const absent = reasons.filter(([r]) => r.startsWith("no-such-relation"));

  assert(
    absent.length > 0,
    "no call site was skipped for naming an absent relation, which contradicts " +
      "the relation audit finding 28 of them. One of the two is not looking at " +
      "the call sites it thinks it is.",
  );
  assert(
    opaque.length > 0,
    "no call site was skipped for an unreadable write payload. That is " +
      "possible — every payload in the corpus could be a literal — and it is " +
      "worth knowing rather than assuming.",
  );
});

